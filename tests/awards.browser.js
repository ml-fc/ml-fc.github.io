    await main.locator('[data-share-voting]').click();
    await page.getByText('Fixture network unavailable',{exact:true}).waitFor();
    assert(!await main.locator('[data-share-voting]').isDisabled(),'Share fetch errors allow retry');
    failParticipation=false;
