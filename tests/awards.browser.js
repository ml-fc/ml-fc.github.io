    await page.screenshot({path:'output/playwright/awards-desk-phone.png'});
    const beforeShare=calls.filter(c=>c.action==='admin_season_awards').length;
    await page.evaluate(()=>{window.fixtureDrawnText=[];window.fixtureDrawnBounds=[];});
    await main.locator('[data-share-voting]').click();
    const votingShare=page.getByRole('dialog',{name:'Share voting image',exact:true});
    await votingShare.locator('img').waitFor();
    await votingShare.locator('img').evaluate(img=>img.decode());
    assert(calls.filter(c=>c.action==='admin_season_awards').length===beforeShare+1,'Share fetches current categories and deadlines');
    const drawn=await page.evaluate(()=>window.fixtureDrawnText.join('\n'));
