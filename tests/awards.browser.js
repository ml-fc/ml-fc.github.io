    assert(shared.name==='mlfc-season-awards-invitation.png' && shared.type==='image/png' && shared.size>1000,'Native share includes PNG file');
    assert(shared.text.includes('Players’ player') && shared.text.includes('21 Dec 2099') && shared.text.includes('#/awards?seasonId=fixture-awards'),'Image caption retains categories, dates and clickable link');
    const invitationDownload=page.waitForEvent('download');
